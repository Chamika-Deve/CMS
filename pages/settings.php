let toastTimer = null;
function showToast(msg, type = 'success') {
    const toast = document.getElementById('liveToast');
    const toastMsg = document.getElementById('toastMsg');
    const toastIcon = document.getElementById('toastIcon');
    if (!toast || !toastMsg) return;

    toastMsg.textContent = msg;
    if (type === 'error') {
        toastIcon.className = 'w-6 h-6 rounded-full bg-red-500/20 text-red-400 flex items-center justify-center text-xs';
        toastIcon.innerHTML = '<i class="fa-solid fa-circle-exclamation"></i>';
    } else {
        toastIcon.className = 'w-6 h-6 rounded-full bg-emerald-500/20 text-emerald-400 flex items-center justify-center text-xs';
        toastIcon.innerHTML = '<i class="fa-solid fa-bolt"></i>';
    }

    toast.classList.remove('hidden', 'translate-y-2');
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => {
        toast.classList.add('hidden', 'translate-y-2');
    }, 2800);
}

function quickLiveToggle(key, isChecked, checkboxEl, badgeId = null, onText = '', offText = '') {
    const value = isChecked ? '1' : '0';
    
    // Update badge visual immediately
    if (badgeId) {
        const badge = document.getElementById(badgeId);
        if (badge) {
            badge.textContent = isChecked ? onText : offText;
            if (key === 'maintenance_mode') {
                badge.className = isChecked ? 'px-2 py-0.5 rounded-full text-[10px] font-extrabold uppercase bg-purple-200 text-purple-800 animate-pulse' : 'px-2 py-0.5 rounded-full text-[10px] font-extrabold uppercase bg-slate-200 text-slate-600';
            } else if (key === 'shop_disabled') {
                badge.className = isChecked ? 'px-2 py-0.5 rounded-full text-[10px] font-extrabold uppercase bg-red-200 text-red-800 animate-pulse' : 'px-2 py-0.5 rounded-full text-[10px] font-extrabold uppercase bg-emerald-100 text-emerald-800';
            }
        }
    }

    fetch('api_status.php', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ key: key, value: value })
    })
    .then(r => r.json())
    .then(data => {
        if (data.success) {
            showToast(data.message || (key + ' updated live!'), 'success');
        } else {
            showToast('Error: ' + (data.error || 'Failed to update'), 'error');
            checkboxEl.checked = !isChecked; // revert
        }
    })
    .catch(err => {
        showToast('Network error updating setting.', 'error');
        checkboxEl.checked = !isChecked; // revert
    });
}

function quickLiveTextUpdate(key, inputEl) {
