    $tables = [];
    $stmt_tbl = $pdo->query("SHOW TABLES");
    while ($row = $stmt_tbl->fetch(PDO::FETCH_NUM)) {
        $tables[] = $row[0];
    }

    $sql_dump = "-- --------------------------------------------------------\n";
    $sql_dump .= "-- TechShop CMS Database Backup Dump\n";
    $sql_dump .= "-- Generated by SuperAdmin (Software Engineer) on " . date('Y-m-d H:i:s') . "\n";
    $sql_dump .= "-- --------------------------------------------------------\n\n";
    $sql_dump .= "SET FOREIGN_KEY_CHECKS=0;\n\n";

    foreach ($tables as $t) {
        $stmt_cr = $pdo->query("SHOW CREATE TABLE `$t`");
        $create_row = $stmt_cr->fetch(PDO::FETCH_NUM);
        $sql_dump .= "\n-- Structure for table `$t`\n";
        $sql_dump .= "DROP TABLE IF EXISTS `$t`;\n";
        $sql_dump .= $create_row[1] . ";\n\n";

        $stmt_data = $pdo->query("SELECT * FROM `$t`");
        $rows = $stmt_data->fetchAll(PDO::FETCH_ASSOC);
        if (!empty($rows)) {
            $sql_dump .= "-- Dumping data for table `$t`\n";
            foreach ($rows as $r) {
                $cols = array_map(fn($c) => "`$c`", array_keys($r));
                $vals = array_map(function($v) use ($pdo) {
                    if (is_null($v)) return "NULL";
                    return $pdo->quote($v);
                }, array_values($r));
                $sql_dump .= "INSERT INTO `$t` (" . implode(', ', $cols) . ") VALUES (" . implode(', ', $vals) . ");\n";
            }
            $sql_dump .= "\n";
        }
    }

    $sql_dump .= "SET FOREIGN_KEY_CHECKS=1;\n";
    
    header('Content-Type: application/sql');
    header('Content-Disposition: attachment; filename="techshop_backup_' . date('Ymd_His') . '.sql"');
    header('Content-Length: ' . strlen($sql_dump));
    echo $sql_dump;
    exit;
}

