            foreach ($system_currencies as &$curr) {
                if ($curr['code'] === $code) {
                    $curr['name'] = $name;
                    $curr['symbol'] = $symbol;
                    $curr['rate'] = $rate;
                    $curr['status'] = $status;
                    $found = true;
                    break;
